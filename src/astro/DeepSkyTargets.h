inline int count() { return int(sizeof(kCatalogue) / sizeof(kCatalogue[0])); }

inline QVariantMap toMap(const Entry &entry)
{
    return {{"id", QString(entry.id)}, {"name", QString(entry.name)},
            {"constellation", QString(entry.constellation)}, {"type", QString(entry.type)},
            {"raHours", entry.raHours}, {"decDeg", entry.decDeg},
            {"magnitude", entry.magnitude}, {"sizeArcmin", entry.sizeArcmin}};
}

// Case-insensitive substring match over designation, name, constellation and
// type; an empty query returns the full catalogue.
inline QVariantList search(const QString &query)
{
    QVariantList result;
    const QString needle = query.trimmed().toUpper();
    for (int i = 0; i < count(); ++i) {
        const Entry &entry = kCatalogue[i];
        if (!needle.isEmpty()) {
            const QString haystack = (QString(entry.id) + " " + entry.name + " "
                                    + entry.constellation + " " + entry.type).toUpper();
            if (!haystack.contains(needle)) continue;
        }
        result.append(toMap(entry));
    }
    return result;
}

inline bool findById(const QString &id, Entry *out)
{
    for (int i = 0; i < count(); ++i) {
        if (id == kCatalogue[i].id) { *out = kCatalogue[i]; return true; }
    }
    return false;
}

